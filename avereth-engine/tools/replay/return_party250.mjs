import fs from 'node:fs';
import assert from 'node:assert/strict';
import {gunzipSync} from 'node:zlib';
import {engineAt} from './replay.mjs';
const {runtime,host,content}=await engineAt(new URL('../..',import.meta.url).pathname);
const source=gunzipSync(fs.readFileSync(process.argv[2])).toString().trimEnd().split('\n').slice(1).map(JSON.parse);
const idx=source.findIndex((m,i)=>i>76 && m.is_user && m.mes.startsWith('I leave my upstairs room'));
assert.ok(idx>0);
const chat=structuredClone(source.slice(0,idx));
const state=()=>host.foldChat(chat).state;
assert.ok(!state().scene.present.includes('npc.ossen'));
chat.push({is_user:true,mes:source[idx].mes,extra:{}});
await runtime.prepareGenerationAsync(chat,content,{llm:async()=>host.rec(source[idx]).plan.raw.at(-1)});
chat.push({is_user:false,mes:source[idx+1].mes,extra:{}});
runtime.processReplyAny(chat,idx+1,content);
await runtime.runExtraction(chat,idx+1,content,async()=>JSON.stringify(host.rec(source[idx+1]).extraction.raw));
assert.equal(state().scene.at,'loc.alderwatch.the_slaked_lime');
assert.ok(state().scene.present.includes('npc.madge'));
assert.ok(state().scene.present.includes('npc.ossen'));
console.log('Juniper: encountered the companion who stayed at the inn');
